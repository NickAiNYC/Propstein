"""Determinism contracts: seeded primitives are stable and TS-parity."""

from __future__ import annotations

from pipeline.determinism import (
    canonical_json,
    fnv1a,
    gauss,
    mulberry32,
    normal_cdf,
    seed_from,
    sha256_hex,
    snapshot_hash,
)


def test_fnv1a_stable_values():
    # Reference values computed from the identical TS implementation.
    assert fnv1a("") == 0x811C9DC5
    assert fnv1a("a") == 0xE40C292C
    assert fnv1a("foobar") == 0xBF9CF968


def test_seed_from_tuple_ordering():
    assert seed_from("a", "b") != seed_from("b", "a")
    assert seed_from("a", "b") == seed_from("a", "b")


def test_mulberry32_sequence_stable():
    # Reference values generated by the TS implementation
    # (src/lib/domain/determinism.ts) — cross-language parity contract.
    rand = mulberry32(20261024)
    seq = [round(rand(), 10) for _ in range(6)]
    assert seq == [
        0.2840708927,
        0.5368913878,
        0.6360740627,
        0.4680839395,
        0.8862529257,
        0.6010156446,
    ]


def test_gauss_reproducible():
    a = gauss(mulberry32(7))
    b = gauss(mulberry32(7))
    assert a == b
    assert -6.0 < a < 6.0


def test_normal_cdf_known_points():
    assert abs(normal_cdf(0.0) - 0.5) < 1e-9
    assert abs(normal_cdf(1.96) - 0.9750021048517795) < 1e-9
    assert normal_cdf(-3.0) < 0.0014


def test_canonical_json_key_order_and_precision():
    doc = {"b": 1, "a": 2, "c": {"z": 0.1234567891, "y": [1.0, 2.5]}}
    assert canonical_json(doc) == '{"a":2,"b":1,"c":{"y":[1,2.5],"z":0.123457}}'


def test_snapshot_hash_stable():
    h1 = snapshot_hash({"x": 1.5, "y": "s"})
    h2 = snapshot_hash({"y": "s", "x": 1.5})
    assert h1 == h2 and len(h1) == 64


def test_sha256_hex_known_vector():
    assert sha256_hex("abc") == (
        "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad"
    )
